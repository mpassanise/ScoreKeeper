import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve('.sites-runtime/frequent-player-tests');mkdirSync(output,{recursive:true});
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','shared/frequent-players.ts','--target','ES2022','--module','commonjs','--strict','--skipLibCheck','--outDir',output],{stdio:'inherit'});
writeFileSync(path.join(output,'package.json'),'{"type":"commonjs"}');
const {parseFrequentPlayers,savePlayer,pickPlayer,createFrequentPlayersStore}=await import(pathToFileURL(path.join(output,'frequent-players.js')).href);
assert.deepEqual(parseFrequentPlayers(null),[]);
assert.throws(()=>parseFrequentPlayers('invalid'));
assert.throws(()=>parseFrequentPlayers('["Mike"," mike "]'),/duplicate/);
assert.deepEqual(savePlayer([],' Mike '),['Mike']);
assert.throws(()=>savePlayer(['Mike'],'MIKE'),/already/);
assert.deepEqual(savePlayer(['Mike','Sam'],'Michael','Mike'),['Michael','Sam']);
assert.throws(()=>savePlayer(['Mike','Sam'],'SAM','Mike'),/already/);
assert.throws(()=>savePlayer([],' '.repeat(5)),/1–30/);
assert.throws(()=>savePlayer([],'x'.repeat(31)),/1–30/);
assert.deepEqual(pickPlayer(['',''],'Mike'),['Mike','']);
assert.deepEqual(pickPlayer(['Mike',''],'Sam'),['Mike','Sam']);
assert.deepEqual(pickPlayer(['Mike','Sam'],'Alex'),['Mike','Sam','Alex']);
assert.deepEqual(pickPlayer(['Mike','Sam'],' mike '),['Mike','Sam']);
assert.throws(()=>pickPlayer(Array.from({length:20},(_,i)=>String(i)),'Another'),/20/);
let raw=null,fail=false,writes=0;
const storage={read:async()=>raw,write:async value=>{writes++;if(fail)throw new Error('Storage unavailable');raw=value}};
let store=createFrequentPlayersStore(storage);await store.load();assert.equal(store.getSnapshot().ready,true);
assert.equal(await store.save(' Mike '),true);assert.equal(await store.save('MIKE'),false);assert.equal(writes,1);
store=createFrequentPlayersStore(storage);await store.load();assert.deepEqual(store.getSnapshot().names,['Mike'],'saved players survive reload');
fail=true;assert.equal(await store.save('Sam'),false);assert.deepEqual(store.getSnapshot().names,['Mike']);assert.match(store.getSnapshot().error,/Storage unavailable/);
fail=false;assert.equal(await store.save('Michael','Mike'),true);assert.deepEqual(store.getSnapshot().names,['Michael']);assert.equal(await store.remove('Michael'),true);assert.deepEqual(store.getSnapshot().names,[]);
raw='broken';store=createFrequentPlayersStore(storage);await store.load();assert.equal(store.getSnapshot().ready,false);const previous=writes;assert.equal(await store.save('Mike'),false);assert.equal(writes,previous,'unreadable storage is not overwritten');
let release;raw='[]';store=createFrequentPlayersStore({read:async()=>raw,write:value=>new Promise(resolve=>{release=()=>{raw=value;resolve()}})});await store.load();const pending=store.save('Mike');assert.equal(await store.save('Sam'),false,'overlapping writes are blocked');release();await pending;assert.deepEqual(store.getSnapshot().names,['Mike']);
console.log('Frequent players: persistence, rename/remove, duplicates, limits, quick picks, storage failure, corrupt data and concurrent writes passed.');

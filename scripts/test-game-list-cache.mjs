import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve('.sites-runtime/game-list-cache-tests');mkdirSync(output,{recursive:true});
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','shared/game-list-cache.ts','--target','ES2022','--module','commonjs','--strict','--skipLibCheck','--outDir',output],{stdio:'inherit'});
writeFileSync(path.join(output,'package.json'),'{"type":"commonjs"}');
const {createGameListCache}=createRequire(import.meta.url)(path.join(output,'game-list-cache.js'));
const data=new Map();let unavailable=false;
const storage={read:async k=>{if(unavailable)throw Error('Unavailable');return data.get(k)||null},write:async(k,v)=>{if(unavailable)throw Error('Unavailable');data.set(k,v)},remove:async k=>data.delete(k)};
const game={id:'game',name:'Phase 10',players:[{id:'p',name:'Mike'}],winner:'low',finished:false,version:1,updated:'2026-10-16',turnCount:0};
let cache=createGameListCache(storage);
await cache.write('alice',[{...game,entries:[{private:'not a summary'}]}, {...game,id:'local',deviceOnly:true}]);
assert.deepEqual(await cache.read('alice'),[game]);
assert.deepEqual(await cache.read('bob'),[],'account lists must remain isolated');
assert.deepEqual(await cache.read(undefined),[],'guest cannot see account cache');
cache=createGameListCache(storage);assert.equal((await cache.read('alice'))[0].name,'Phase 10','cache survives app restart');
const pending=cache.write('alice',[{...game,version:2}]);const clear=cache.clear('alice');await Promise.all([pending,clear]);assert.deepEqual(await cache.read('alice'),[],'sign-out clearing wins over queued writes');
await cache.write('bob',[game]);await cache.clear('alice');assert.equal((await cache.read('bob')).length,1);
unavailable=true;assert.deepEqual(await cache.read('bob'),[],'cache errors must not prevent startup');await assert.rejects(cache.write('bob',[game]));unavailable=false;
await cache.write('bob',[{...game,version:3}]);assert.equal((await cache.read('bob'))[0].version,3,'write queue recovers after storage error');
for(const [k]of data)data.set(k,'invalid');assert.deepEqual(await cache.read('bob'),[]);
for(const [k]of data)data.set(k,JSON.stringify({version:1,games:[null,{},game]}));assert.deepEqual(await cache.read('bob'),[game]);
console.log('Game list cache: account isolation, guest exclusion, summary-only storage, restart, logout ordering, corruption and storage failures passed.');

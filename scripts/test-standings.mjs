import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve('.sites-runtime/standings-tests');mkdirSync(output,{recursive:true});
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','shared/standings.ts','--target','ES2022','--module','commonjs','--strict','--skipLibCheck','--outDir',output],{stdio:'inherit'});
writeFileSync(path.join(output,'package.json'),'{"type":"commonjs"}');
const {gameStandings}=createRequire(import.meta.url)(path.join(output,'standings.js'));
const players=['Mike','Stephanie','Alex'].map((name,i)=>({id:String(i),name}));
const game={players,winner:'high',finished:false};
let result=gameStandings(game,{'0':20,'1':50,'2':10});assert.deepEqual(result.players.map(p=>p.player.name),['Stephanie','Mike','Alex']);assert.equal(result.margin,'Stephanie leads by 30 points');
assert.deepEqual(players.map(p=>p.name),['Mike','Stephanie','Alex'],'ranking must never mutate tile/turn order');
result=gameStandings({...game,winner:'low'},{'0':20,'1':50,'2':10});assert.equal(result.margin,'Alex leads by 10 points');assert.deepEqual(result.players.map(p=>p.score),[10,20,50]);
result=gameStandings(game,{'0':50,'1':50,'2':10});assert.deepEqual(result.players.map(p=>p.rank),[1,1,3]);assert.equal(result.margin,'Tied for the lead · 2 players');assert.equal(result.players[0].player.id,'0','ties preserve turn order');
result=gameStandings({...game,winner:'low'},{'0':-5,'1':-4,'2':0});assert.equal(result.margin,'Mike leads by 1 point');
assert.equal(gameStandings({...game,finished:true},{'0':1,'1':4,'2':2}).margin,'Stephanie won by 2 points');
assert.equal(gameStandings(game,{}).margin,'Tied for the lead · 3 players');
assert.equal(gameStandings({...game,players:[]},{}).margin,'');assert.equal(gameStandings({...game,players:[players[0]]},{}).margin,'');
console.log('Standings: high/low rules, margins, ties, stable tile order, negative scores, completion and empty games passed.');

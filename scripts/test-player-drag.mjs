import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const output=path.resolve('.sites-runtime/drag-tests');mkdirSync(output,{recursive:true});
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','mobile/drag-target.ts','--target','ES2022','--module','commonjs','--skipLibCheck','--outDir',output],{stdio:'inherit'});
writeFileSync(path.join(output,'package.json'),'{"type":"commonjs"}');
const {dragTarget}=await import(pathToFileURL(path.join(output,'drag-target.js')).href);
const rows=[0,1,2].map(index=>({index,x:20,y:200+index*64,width:300,height:54}));
assert.equal(dragTarget(rows,0,0,0),0,'a tap keeps the same player');
assert.equal(dragTarget(rows,0,0,65),1,'setup row moves down one slot');
assert.equal(dragTarget(rows,2,0,-128),0,'last setup row can move to first');
const cards=[0,1,2,3].map(index=>({index,x:20+(index%2)*166,y:300+Math.floor(index/2)*220,width:156,height:205}));
assert.equal(dragTarget(cards,0,166,0),1,'grid cards can move horizontally');
assert.equal(dragTarget(cards,0,166,220),3,'grid cards can move diagonally');
assert.equal(dragTarget(cards,0,0,0),0,'a handle below the card does not move the player without a drag');
assert.equal(dragTarget([],2,100,100),2,'missing measurements never choose a different player');
console.log('Player drag target checks passed for taps, setup rows, horizontal/diagonal cards and missing measurements.');
